export function findWorkflow(slug: string) {
  return WORKFLOWS.find((w) => w.slug === slug);
}

export function workflowForPath(pathname: string) {
  return WORKFLOWS.find((w) => w.paths.some((p) => pathname === p || pathname.startsWith(p + "/")));
}
